#!/usr/bin/env python3
"""Regenerate every skills document from the SKILL.md files themselves.

Single source of truth = each skill's frontmatter:
    name · argument-hint · disable-model-invocation · metadata.group · metadata.phrase

  gen_docs.py --check     report drift only: skills missing phrase/group, names absent from GUIDE.md
  gen_docs.py             write SKILLS.md, refresh the README table, build both PDFs

Run with:  uv run --with reportlab python gen_docs.py        (PDFs need reportlab)
Outputs (all in ~/.claude/skills/lab/):
    SKILLS.md              generated index of personal + lab skills
    README.md              region between <!-- skills:start --> and <!-- skills:end -->
    lab-reference.pdf      the lab process, one line per command, with arguments
    skills-reference.pdf   everything typeable on this machine
"""
import json
import re
import sys
from datetime import date
from pathlib import Path

SK = Path.home() / ".claude" / "skills"
LAB = SK / "lab"
TODAY = date.today().isoformat()

GROUPS = [  # key, title, blurb
    ("reflex", "Reflexes", "personal skills: read the conversation, answer in a few lines, never derail the task"),
    ("start", "Start", ""),
    ("idea", "When you have an idea", ""),
    ("know", "Knowing what exists", ""),
    ("decide", "Deciding", ""),
    ("trust", "Trusting a result", ""),
    ("organise", "Organising and teaching", "manual only: these never run on their own and cost no context until typed"),
    ("docs", "Keeping the docs current", ""),
]


# --------------------------------------------------------------------------- collect
def frontmatter(path: Path) -> dict:
    text = path.read_text()
    if not text.startswith("---\n"):
        return {}
    block = text[4:text.index("\n---\n", 4)]
    out, section = {}, None
    for line in block.splitlines():
        if not line.strip():
            continue
        if line.startswith("  ") and section:
            k, _, v = line.strip().partition(":")
            out[section][k.strip()] = v.strip().strip('"')
        else:
            k, _, v = line.partition(":")
            v = v.strip()
            if v == "":
                section = k.strip()
                out[section] = {}
            else:
                section = None
                out[k.strip()] = v.strip('"') if not v.startswith('"<') else v
    return out


def collect():
    skills = []
    for f in sorted(SK.glob("*/SKILL.md")):
        if f.parent.name in ("lab", "synced"):
            continue
        skills.append(("personal", f))
    for f in sorted((LAB / "skills").glob("*/SKILL.md")):
        skills.append(("lab", f))
    rows = []
    for scope, f in skills:
        fm = frontmatter(f)
        name = fm.get("name") or f.parent.name
        meta = fm.get("metadata") if isinstance(fm.get("metadata"), dict) else {}
        rows.append({
            "scope": scope, "name": name,
            "cmd": f"/{name}" if scope == "personal" else f"/lab:{name}",
            "hint": fm.get("argument-hint", ""),
            "manual": str(fm.get("disable-model-invocation", "")).lower() in ("true", "yes", "on", "1"),
            "group": meta.get("group", ""), "phrase": meta.get("phrase", ""), "path": f,
        })
    return rows


def check(rows):
    problems = []
    guide = (LAB / "GUIDE.md").read_text() if (LAB / "GUIDE.md").exists() else ""
    known = {g[0] for g in GROUPS}
    for r in rows:
        if not r["phrase"]:
            problems.append(f"{r['cmd']}: no metadata.phrase  ({r['path']})")
        if r["group"] not in known:
            problems.append(f"{r['cmd']}: metadata.group '{r['group']}' is not one of {sorted(known)}")
        if r["cmd"] not in guide and f"`{r['name']}`" not in guide:
            problems.append(f"{r['cmd']}: not mentioned in GUIDE.md (add a row by hand — the guide is curated)")
    return problems


def grouped(rows, scope=None):
    for key, title, blurb in GROUPS:
        members = [r for r in rows if r["group"] == key and (scope is None or r["scope"] == scope)]
        if members:
            yield key, title, blurb, members


# --------------------------------------------------------------------------- markdown
def md_table(rows):
    out = ["| Command | Arguments | What it does |", "|---|---|---|"]
    for r in rows:
        hint = r["hint"].replace("|", "\\|")
        out.append(f"| `{r['cmd']}`{' *(manual)*' if r['manual'] else ''} | {('`' + hint + '`') if hint else ''} | {r['phrase']} |")
    return "\n".join(out)


def write_markdown(rows):
    parts = [f"# Skills index\n\n*Generated by `reference/gen_docs.py` on {TODAY} from each skill's frontmatter — "
             "do not edit by hand; edit the skill's `metadata.phrase` / `argument-hint` and run `/update-docs`.*\n"]
    for _, title, blurb, members in grouped(rows):
        parts.append(f"## {title}\n" + (f"*{blurb}*\n\n" if blurb else "\n") + md_table(members) + "\n")
    (LAB / "SKILLS.md").write_text("\n".join(parts))

    readme = LAB / "README.md"
    text = readme.read_text()
    block = ("<!-- skills:start -->\n*Generated — run `/update-docs` after adding or changing a skill.*\n\n"
             + "\n\n".join(f"**{t}**\n\n{md_table(m)}" for _, t, _, m in grouped(rows)) + "\n<!-- skills:end -->")
    if "<!-- skills:start -->" in text:
        text = re.sub(r"<!-- skills:start -->.*?<!-- skills:end -->", lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n## All skills\n\n" + block + "\n"
    readme.write_text(text)


# --------------------------------------------------------------------------- pdf
def build_pdfs(rows):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.pdfmetrics import registerFontFamily
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    from xml.sax.saxutils import escape as esc

    F = "/System/Library/Fonts/Supplemental/"
    pdfmetrics.registerFont(TTFont("U", F + "Arial Unicode.ttf"))
    pdfmetrics.registerFont(TTFont("B", F + "Arial Bold.ttf"))
    pdfmetrics.registerFont(TTFont("M", F + "Courier New Bold.ttf"))
    registerFontFamily("U", normal="U", bold="B", italic="U", boldItalic="B")
    INK, MUTED = colors.HexColor("#1d1b18"), colors.HexColor("#6b655c")
    RULE, ACCENT, BAND = colors.HexColor("#d9d2c5"), colors.HexColor("#a5481f"), colors.HexColor("#f4efe6")

    def st(name, **kw):
        base = dict(fontName="U", fontSize=9, leading=12.2, textColor=INK)
        base.update(kw)
        return ParagraphStyle(name, **base)

    S = {"title": st("t", fontName="B", fontSize=22, leading=26), "sub": st("s", fontSize=10, leading=14, textColor=MUTED),
         "h": st("h", fontName="B", fontSize=11.5, leading=15, textColor=ACCENT, spaceBefore=9, spaceAfter=1),
         "where": st("w", fontSize=8, leading=10.5, textColor=MUTED, spaceAfter=3), "p": st("p"),
         "small": st("sm", fontSize=8, leading=10.5, textColor=MUTED), "cmd": st("c", fontName="M", fontSize=8.2, leading=11),
         "what": st("wh", fontSize=8.7, leading=11.4), "mono": st("m", fontName="M", fontSize=8, leading=10.8)}
    P = lambda t, s="p": Paragraph(t, S[s])

    def table(pairs, widths=(58 * mm, 116 * mm)):
        t = Table([[P(c, "cmd"), P(w, "what")] for c, w in pairs], colWidths=widths, hAlign="LEFT")
        t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 0), (-1, -2), 0.4, RULE),
                               ("TOPPADDING", (0, 0), (-1, -1), 2.8), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.8),
                               ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 5)]))
        return t

    def band(text, style="mono"):
        t = Table([[P(text, style)]], colWidths=[174 * mm])
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), BAND), ("LEFTPADDING", (0, 0), (-1, -1), 7),
                               ("RIGHTPADDING", (0, 0), (-1, -1), 7), ("TOPPADDING", (0, 0), (-1, -1), 6),
                               ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        return t

    def section(title, where, pairs, note=None):
        block = [P(title, "h")] + ([P(where, "where")] if where else [Spacer(1, 2)]) + [table(pairs)]
        if note:
            block += [Spacer(1, 2), P(note, "small")]
        return KeepTogether(block)

    def skill_pairs(members, with_hint=True):
        out = []
        for r in members:
            what = esc(r["phrase"])
            if with_hint and r["hint"]:
                what += f"<br/><font name='M' size='7.6' color='#6b655c'>{esc(r['hint'])}</font>"
            out.append((esc(r["cmd"]), what))
        return out

    def footer(label):
        def draw(canvas, doc):
            canvas.saveState()
            canvas.setFont("U", 7.5)
            canvas.setFillColor(MUTED)
            canvas.drawString(18 * mm, 10 * mm, f"{label} · generated {TODAY} by /update-docs")
            canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"{doc.page}")
            canvas.restoreState()
        return draw

    def build(path, story, label):
        SimpleDocTemplate(str(path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                          bottomMargin=17 * mm, title=label, author="Joseph Giordano-Dinh (SEVEL LABS)"
                          ).build(story, onFirstPage=footer(label), onLaterPages=footer(label))

    tldr = KeepTogether([
        P("How every step ends in the terminal", "h"), Spacer(1, 2),
        band("(Correction, if any &mdash; always first)<br/>TL;DR &nbsp;&nbsp;&nbsp;&nbsp; what happened, and the number<br/>"
             "! Flagged &nbsp; what could make it wrong: assumed inputs, anything not measured on the real target<br/>"
             "→ Implies &nbsp; what it changes: names a file, a stage, or a hypothesis<br/>"
             "? Deeper &nbsp;&nbsp; what to study next, each with a price &mdash; in Claude time, machine time, or your time"),
        Spacer(1, 3),
        P("If Flagged is empty or Deeper has no prices, push back. Every number is <b>measured</b>, <b>sourced</b>, "
          "<b>derived</b> or <b>assumed</b>, and says which. Plans open with an ETA as a clock time; the status bar shows "
          "logged plans and watched jobs live.", "small")])

    version = json.loads((LAB / ".claude-plugin/plugin.json").read_text()).get("version", "?")
    n_lab = sum(1 for r in rows if r["scope"] == "lab")

    # ---- lab-reference.pdf
    story = [P("lab", "title"),
             P(f"A first-principles research process for Claude Code &mdash; command reference, v{version}", "sub"), Spacer(1, 7),
             P("Every design choice is a hypothesis tied to a <b>unit</b>. Non-trivial work <b>starts with a plan and a challenge</b>. "
               "Every step <b>ends in a file</b> and a four-part TL;DR. Every open question carries a <b>price</b>. Claude applies this "
               "in every project on this machine (<font name='M' size='8'>~/.claude/CLAUDE.md</font>); bug fixes, one-liners and "
               "questions are exempt."), Spacer(1, 5),
             band("(draft) → derive → explore → challenge → record → (plan → build → repro-check → stage-report) → tldr")]
    for key, title, blurb, members in grouped(rows):
        if key == "reflex":
            continue
        story.append(section(title, blurb, skill_pairs([m for m in members if m["scope"] == "lab"] or members)))
    story.append(section("Reflexes &mdash; personal skills, short names", "", skill_pairs([r for r in rows if r["group"] == "reflex"], with_hint=False)))
    story += [tldr, KeepTogether([
        P("Where things land (defaults; a project's profile can repoint any of them)", "h"), Spacer(1, 2),
        band("docs/lab/profile.md &nbsp;&nbsp;&nbsp;&nbsp;&nbsp; the project's metric, units, paths, house rules<br/>"
             "docs/lab/decisions.md &nbsp;&nbsp;&nbsp; why; ends with \"Open / not yet decided\"<br/>"
             "docs/lab/open.md &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; the ledger: item, price, raised by, status<br/>"
             "docs/lab/ideas.md, ideas/ &nbsp;draft-ideas lists and prototype briefs<br/>"
             "docs/lab/derivations/ &nbsp;&nbsp;&nbsp; derive-ansatz, apply-academia<br/>"
             "docs/lab/explorations/ &nbsp;&nbsp; explore-and-report, novelty-claim<br/>"
             "docs/lab/reports/ &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; stage reports, ablation plans, integrity audits<br/>"
             "docs/lab/rules/ &nbsp;bom/ &nbsp;partners/"), Spacer(1, 4),
        P("Plugin: ~/.claude/skills/lab/ &nbsp;&middot;&nbsp; user guide: GUIDE.md &nbsp;&middot;&nbsp; decisions and test log: README.md "
          "&nbsp;&middot;&nbsp; full index: SKILLS.md. \"Unknown command: /lab:&hellip;\" means the session predates the skill: /reload-plugins.", "small")])]
    build(LAB / "lab-reference.pdf", story, "lab — command reference")

    # ---- skills-reference.pdf
    where = Table([[P(a, "mono"), P(b, "mono"), P(c, "what")] for a, b, c in [
        ("~/.claude/skills/&lt;name&gt;", "/name", "personal: every project, picked up live"),
        ("~/.claude/skills/lab/skills/&lt;name&gt;", "/lab:name", "plugin: every project; /reload-plugins after adding one"),
        ("&lt;repo&gt;/.claude/skills/&lt;name&gt;", "/name", "project: that repo only; wins over a /lab: twin"),
        ("bundled with Claude Code", "/name", "everywhere"),
        ("synced from your claude.ai account", "/anthropic-skills:name", "everywhere you are signed in")]],
        colWidths=[62 * mm, 46 * mm, 66 * mm], hAlign="LEFT")
    where.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), BAND), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("LEFTPADDING", (0, 0), (-1, -1), 7), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                               ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
    story = [P("Skills reference", "title"),
             P(f"Everything you can type in Claude Code on this machine &mdash; one phrase each. Generated {TODAY}.", "sub"), Spacer(1, 7),
             P("A <b>skill</b> is a text file of instructions Claude loads when you type its name &mdash; or on its own, when your "
               "request matches its description. Where the file lives decides its name and where it works:"), Spacer(1, 4), where,
             section("Reflexes &mdash; yours, personal", "~/.claude/skills/ &nbsp;&middot;&nbsp; read the conversation, answer briefly, never derail the task",
                     skill_pairs([r for r in rows if r["scope"] == "personal"]),
                     "rectify and update-context share one triage: trivial &rarr; applied at once; consequential &rarr; impact list, then always "
                     "asks; conflicts with the evidence &rarr; flagged first. The status bar shows logged ETAs and watched jobs with no command at all.")]
    for key, title, blurb, members in grouped(rows, scope="lab"):
        story.append(section(f"lab &mdash; {title.lower()}", "~/.claude/skills/lab/" + (f" &nbsp;&middot;&nbsp; {blurb}" if blurb else ""),
                             skill_pairs(members, with_hint=False)))
    static = json.loads((Path(__file__).parent / "static_skills.json").read_text())
    for sec in static:
        story.append(section(sec["title"], sec["where"], [(esc(c), w) for c, w in sec["rows"]], sec.get("note")))
    story.append(KeepTogether([Spacer(1, 5),
        P("Easy to mix up: <b>/last</b> reads the chat (what did you just do); <b>/lab:tldr</b> reads the project's files (where are we); "
          "<b>/big-job</b> shows the phase checklist of the job we left (what is left); <b>/huh</b> explains one term. And: /init vs /lab:init, /security-review vs /lab:integrity-audit, /update-config vs "
          "/update-context vs /update-docs.", "small"), Spacer(1, 3),
        P(f"Personal and lab sections are generated from the skills' own frontmatter ({n_lab} lab skills). Bundled, synced and "
          "repo-local sections are a hand-kept snapshot (reference/static_skills.json) &mdash; /skills shows the live list. "
          "On a Pro subscription skills use time and usage quota, not money.", "small")]))
    build(LAB / "skills-reference.pdf", story, "Skills reference")


# --------------------------------------------------------------------------- main
if __name__ == "__main__":
    rows = collect()
    problems = check(rows)
    print(f"{len(rows)} skills: {sum(r['scope'] == 'personal' for r in rows)} personal, {sum(r['scope'] == 'lab' for r in rows)} lab")
    for p in problems:
        print("  DRIFT  " + p)
    if "--check" in sys.argv:
        sys.exit(1 if problems else 0)
    write_markdown(rows)
    print("wrote SKILLS.md, README.md table")
    try:
        build_pdfs(rows)
        print("wrote lab-reference.pdf, skills-reference.pdf")
    except ModuleNotFoundError:
        print("PDFs skipped: reportlab missing — run with:  uv run --with reportlab python", __file__)
        sys.exit(2)
